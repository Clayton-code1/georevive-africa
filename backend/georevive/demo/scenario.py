"""Build the 'complete' end state of the master demo path from the clean state.

Everything is generated by the real pipeline from real registered data. Fact approvals made by
this script are clearly labelled as scripted demo approvals (to be confirmed by the Geoscience Lead)."""

from __future__ import annotations

from sqlalchemy import func, select

from ..db import session_scope
from ..models import ClaimReport, Document, FactReview, Layer, ModelRun, Share, User
from . import snapshots

SCRIPT_NOTE = "Pre-loaded demo scenario (scripted approval) - Geoscience Lead to confirm"
AUTO_APPROVE_TYPES = ("mine", "assay", "rock_unit", "location_desc", "coordinate", "commodity", "farm")


def demo_data_present() -> bool:
    with session_scope() as db:
        return any(db.scalar(select(func.count()).select_from(m)) for m in (Document, ModelRun, ClaimReport, Share))


def build() -> dict:
    from .. import audit
    from ..api.routers.dataroom import licence_check
    from ..config import get_settings
    from ..prospect import engine
    from ..registry import abspath, rel
    from ..reports import claim_analysis
    from ..reports.claim_pdf import build_pdf
    from ..reports.mapsnap import snapshot
    from ..rescue import pipeline
    from ..rescue.samples import list_samples, sample_path

    snapshots.restore("clean")
    log: dict = {}
    s = get_settings()
    with session_scope() as db:
        # 1. data rescue on the first sample page
        samples = list_samples()
        if samples:
            sm = samples[0]
            doc = pipeline.create_document(db, sample_path(sm["id"]), sm["source_id"], sm["title"], "analyst")
            page = pipeline.get_or_create_page(db, doc, 1)
            pipeline.process_page(db, page)
            n = 0
            for f in page.facts:
                if f.type in AUTO_APPROVE_TYPES and f.confidence >= 0.7 and f.lon is not None:
                    before = {"status": f.status}
                    f.status = "approved"
                    db.add(
                        FactReview(
                            fact_id=f.id,
                            username="geologist",
                            action="approve",
                            before=before,
                            after={"status": "approved"},
                            comment=SCRIPT_NOTE,
                        )
                    )
                    audit.log(db, "geologist", "geologist", "approve", "fact", f.id, {"scenario": True})
                    n += 1
            pipeline.rebuild_rescued_layer(db)
            log["document"] = doc.id
            log["approved_facts"] = n
        # 2. prospectivity (knowledge-driven)
        run = engine.run_model(db, "fuzzy", "analyst")
        audit.log(db, "analyst", "analyst", "model_run", "model_run", run.id, {"method": "fuzzy", "scenario": True})
        log["run"] = run.id
        # 3. claim report around the top target
        db.flush()
        top = min(run.targets, key=lambda t: t.rank) if run.targets else None
        if top:
            poly = claim_analysis.square_around(top.lon, top.lat, 500, s.working_crs)
            a = claim_analysis.analyse(db, poly, "Demo claim at target 1")
            rep = ClaimReport(username="miner", name=a["name"], polygon=poly, run_id=run.id, summary={}, pdf_path="")
            db.add(rep)
            db.flush()
            out = s.path("reports_dir") / "generated"
            png = out / f"claim_{rep.id}_map.png"
            a["map_attributions"] = snapshot(poly, png, abspath(run.grid_path), title=a["name"])
            rep.pdf_path = rel(build_pdf(a, png, out / f"claim_{rep.id}.pdf", prepared_for="Small-scale Miner (miner)"))
            rep.summary = {"area_ha": a["area_ha"], "district": a.get("district"), "province": a.get("province")}
            audit.log(db, "miner", "miner", "claim_report", "claim_report", rep.id, {"scenario": True})
            log["claim_report"] = rep.id
        # 4. data room: share open-licence layers with the investor
        inv = db.scalar(select(User).where(User.username == "investor"))
        adm = db.scalar(select(User).where(User.username == "admin"))
        shared = []
        for lid in ("prospectivity_gold", "mrds_occurrences", "s2_iron_oxide", "admin_adm2", "dem_hillshade"):
            layer = db.get(Layer, lid)
            if layer is not None and licence_check(layer.source.licence)["ok"] and inv and adm:
                db.add(Share(layer_id=lid, user_id=inv.id, granted_by=adm.id, note="Demo scenario"))
                audit.log(db, "admin", "admin", "share", "layer", lid, {"with": "investor", "scenario": True})
                shared.append(lid)
        log["shared"] = shared
    snapshots.save("complete", note=str(log))
    return log
